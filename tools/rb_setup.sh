#!/usr/bin/env bash
# One-time asset setup (free, MIT): Microsoft Rocketbox mocap clips (+ optional avatars) → public/rb, plus Prompt fonts → public/fonts.
# usage: bash tools/rb_setup.sh                      # 40 clips × 2 genders (everything the toon cast + lockdown episodes use)
#        CLIPS="run_fast_01 cheer_01" bash tools/rb_setup.sh       # add more clips (names without m_/f_ and .max.fbx)
#        AVATARS="Business_Male_01 Police_Male_01" bash tools/rb_setup.sh  # also convert textured Rocketbox avatars
#        RB_DIR=/path/to/existing/clone bash tools/rb_setup.sh  # reuse a clone
set -euo pipefail
cd "$(dirname "$0")/.."
RB_DIR=${RB_DIR:-.rocketbox}
BASE="idle_neutral_01 idle_look_around_01 work_table work_mid sit_chair_idle_neutral_01 sit_chair_gestic_thoughtful sit_chair_gestic_shrug_01 sit_chair_idle_relaxed_01 sit_table_idle_neutral_01 cell_phone_textmessage cell_phone_talk_01 drink_drinking gestic_talk_neutral_01 gestic_talk_neutral_02 gestic_listen_neutral_01 gestic_listen_accept_01 gestic_laugh_loud documents_check documents_note wave_01 gestic_presentation_right_01 gestic_thoughtful_01 trolley_idle idle_dust_01 hold_bag_idle hold_bag_idle_01 walk_neutral_01 crouch_idle crouch_gestic idle_nervous_01 idle_nervous_02 sit_table_idle_nervous_01 sit_chair_idle_nervous_01 sit_table_idle_look_around gestic_talk_nervous_01 gestic_listen_nervous_01 listen_door try_door_inwards idle_look_around_02 sit_table_idle_neutral_02 sit_table_idle_touch_face run_neutral_01 idle_yawn_01 idle_stretch_arms_01 sit_chair_idle_yawn gestic_talk_angry_01 idle_angry_01 knock_door"
WANT="$BASE ${CLIPS:-}"
if [ ! -d "$RB_DIR/.git" ]; then git clone --filter=blob:none --no-checkout --depth 1 https://github.com/microsoft/Microsoft-Rocketbox "$RB_DIR"; fi
ALL=$(git -C "$RB_DIR" ls-tree -r --name-only HEAD)
P="LICENSE.md"
for b in $WANT; do for g in m f; do
  f=$(echo "$ALL" | grep -E "^Assets/Animations/all_animations_max_motextr_(static|xy)/${g}_${b}\.max\.fbx$" | head -1 || true)
  [ -n "$f" ] && P="$P $f"
done; done
for a in ${AVATARS:-}; do
  d=$(echo "$ALL" | grep -E "^Assets/Avatars/[^/]+/$a/Export/$a\.fbx$" | head -1 | sed 's|/Export/.*||' || true)
  [ -z "$d" ] && { echo "avatar not found: $a"; continue; }
  P="$P $d/Export/$a.fbx $(echo "$ALL" | grep -E "^$d/Textures/.*_color\.tga$" | tr '\n' ' ')"
done
echo "checking out $(echo $P | wc -w) files from Rocketbox…"
git -C "$RB_DIR" -c advice.detachedHead=false checkout HEAD -- $P 2>&1 | grep -v "Auto packing\|git help gc" || true
mkdir -p public/rb public/fonts
cp "$RB_DIR/LICENSE.md" public/rb/LICENSE-Rocketbox.md
node tools/rb_convert.mjs "$RB_DIR" public/rb 2>&1 | grep -E "^(anims|avatar)" || true
python3 - <<'PY'
import json, os
m = json.load(open('public/rb/manifest.json'))
for a, v in m['avatars'].items(): v['tex'] = sorted(os.listdir(f'public/rb/av/{a}'))
json.dump(m, open('public/rb/manifest.json', 'w'), indent=1)
open('src/pov/cast/rbManifest.ts', 'w').write('// generated by tools/rb_setup.sh\nexport const RB = ' + json.dumps(m) + ' as const;\n')
print('manifest:', len(m['clips']['m']), 'male clips,', len(m['clips']['f']), 'female clips,', len(m['avatars']), 'avatars')
PY
for w in 400 600 700; do for s in thai latin; do cp "node_modules/@fontsource/prompt/files/prompt-$s-$w-normal.woff2" "public/fonts/Prompt-$s-$w.woff2"; done; done
echo "setup done → public/rb, public/fonts"
